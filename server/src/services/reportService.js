// ─── PDF export (professional layout) ───────────────────────────────────────────
//
// PERBAIKAN LAYOUT (v2):
//   1. Kartu statistik TIDAK lagi meluber keluar halaman. Sebelumnya 7 kartu
//      × 120pt + gap 10pt = 900pt > lebar halaman A4 landscape (842 - 72
//      margin = 770pt), sehingga kartu terakhir terpotong di tepi kanan.
//      Sekarang lebar kartu dihitung dinamis agar pas di area konten.
//   2. Footer dicetak pada SETIAP halaman (dengan nomor halaman), bukan
//      hanya halaman terakhir. Sebelumnya halaman terakhir bisa kosong
//      jika tabel tepat habis di batas halaman.
//   3. Ditambah section yang sebelumnya hilang di PDF: rincian keterlambatan,
//      rincian mode verifikasi, dan log kejadian (dibatasi 200 baris).
//   4. Baris tabel diberi garis pemisah + zebra, dan tabel diberi border
//      luar tipis sehingga terlihat rapi seperti laporan resmi.
//   5. Setiap tabel dimulai ulang dengan header berulang di halaman baru.
//
// Lebar kolom dihitung dari teks TERPANJANG di header dan data, bukan angka
// tetap, supaya tidak ada teks yang menabrak kolom sebelahnya.
const PDF_STYLE = {
  navy:        '#1E3A8A',
  navyDark:    '#1E40AF',
  slate900:    '#0F172A',
  slate700:    '#334155',
  slate500:    '#64748B',
  slate400:    '#94A3B8',
  slate200:    '#E2E8F0',
  slate50:     '#F8FAFC',
  red:         '#B91C1C',
  redLight:    '#FEF2F2',
  green:       '#15803D',
  greenLight:  '#F0FDF4',
  amber:       '#B45309',
  amberLight:  '#FFFBEB',
};

/**
 * Hitung lebar kolom PDF dari teks terpanjang (header + isi).
 * Sisa ruang halaman dibagi proporsional ke kolom yang masih lapar.
 * @returns {number[]} lebar tiap kolom dalam poin
 */
function layoutPdfColumns(doc, headers, rows, opts = {}) {
  const {
    fontSize = 7, headFontSize = 7.5, pageW = 500, minWidth = 14,
    maxWidth = 110, gap = 2,
  } = opts;

  const n = headers.length;
  const need = headers.map((h, i) => {
    let w = doc.widthOfString(String(h), { size: headFontSize });
    for (const r of rows) {
      if (r[i] == null) continue;
      // Sel multi-baris diukur per baris (lebar terpanjang), bukan seluruh
      // string sekaligus — widthOfString pada string berisi \n tidak valid.
      const parts = String(r[i]).split('\n');
      for (const part of parts) {
        w = Math.max(w, doc.widthOfString(part, { size: fontSize }));
      }
    }
    return Math.min(maxWidth, Math.ceil(w) + gap * 2);
  });

  const MIN = headers.map(() => minWidth);
  let total = need.reduce((a, b) => a + b, 0);
  const avail = pageW - gap * (n - 1);
  if (total < avail) {
    const extra = need.map((w, i) => Math.max(0, w - MIN[i]));
    const extraSum = extra.reduce((a, b) => a + b, 0);
    const pool = avail - total;
    if (extraSum > 0) {
      for (let i = 0; i < n; i++) need[i] += Math.floor((extra[i] / extraSum) * pool);
    }
  }
  total = need.reduce((a, b) => a + b, 0);
  if (total > avail) {
    // Skala proporsional supaya seluruh tabel muat di halaman.
    const k = avail / total;
    for (let i = 0; i < n; i++) need[i] = Math.max(minWidth, Math.floor(need[i] * k));
  }
  return need;
}

/**
 * Gambar satu tabel PDF dengan header berulang, zebra, dan border.
 *
 * @param {object} doc     dokumen PDFKit
 * @param {object} opts
 * @param {string[]} opts.headers
 * @param {Array[]} opts.rows
 * @param {number[]} opts.cols     lebar kolom (dari layoutPdfColumns)
 * @param {number} opts.x          posisi kiri tabel
 * @param {number} opts.y          posisi atas tabel
 * @param {number} opts.pageH      tinggi halaman
 * @param {number} opts.bottom    ruang bawah sebelum footer
 * @param {number[]} opts.centerCols indeks kolom yang rata tengah
 * @param {number[]} opts.boldCols  indeks kolom yang tebal
 * @param {function} opts.cellColor (value, colIndex, rowIndex) → hex|null
 * @param {function} opts.rowFill   (rowIndex, cells) → hex|null
 */
function drawPdfTable(doc, opts) {
  const {
    headers, rows, cols, x, y, pageH, bottom = 60,
    centerCols = [], boldCols = [], headSize = 7.5, bodySize = 7,
    rowH = 16, headH = 18, cellColor = null, rowFill = null,
    maxRows = Infinity, onNewPage = null,
  } = opts;

  const tableW = cols.reduce((a, b) => a + b, 0);
  let sy = y;

  // ── Baris multi-baris (dynamic row height) ────────────────────────────────
  // Beberapa sel memuat teks 2 baris (judul + detail). Bila baris tabel tetap
  // heights-nya, baris kedua menimpa baris berikutnya. Karena itu tinggi baris
  // dihitung per baris: max(tinggi tetap, tinggi teks multi-baris + padding).
  const PAD_Y = 4;
  const LINE_GAP = 1.5;
  // Tinggi baris dihitung per baris: max(tinggi tetap, tinggi teks multi-baris +
  // padding). Sel yang memuat '\n' (judul + detail) boleh wrap; sel lain tetap
  // satu baris dan dipotong dengan ellipsis.
  const rowHeight = (cells) => {
    let h = rowH;
    cells.forEach((val, i) => {
      const s = String(val ?? '');
      if (!s.includes('\n')) return;
      const need = doc.heightOfString(s, { width: cols[i] - 4, lineGap: LINE_GAP }) + PAD_Y * 2;
      if (need > h) h = need;
    });
    return Math.ceil(h);
  };

  const drawHead = (yy) => {
    doc.rect(x, yy, tableW, headH).fill(PDF_STYLE.navy);
    let cx = x;
    headers.forEach((h, i) => {
      doc.fillColor('white').fontSize(headSize).font('Helvetica-Bold')
        .text(String(h), cx + 2, yy + 4, {
          width: cols[i] - 4,
          align: centerCols.includes(i) ? 'center' : 'left',
          ellipsis: true,
          lineBreak: false,
        });
      cx += cols[i];
    });
    doc.rect(x, yy, tableW, headH).stroke(PDF_STYLE.navy);
    return yy + headH;
  };

  sy = drawHead(sy);

  // Segmen tabel per halaman: border luar harus digambar per segmen, bukan
  // satu rect dari y sampai sy — kalau tabel pecah ke halaman baru, satu
  // garis vertikal besar akan melintasi batas halaman.
  const segments = [];
  let segTop = sy;

  const shown = rows.slice(0, maxRows);
  shown.forEach((cells, idx) => {
    const rh = rowHeight(cells);
    if (sy + rh > pageH - bottom) {
      segments.push({ top: segTop, bottom: sy });
      doc.addPage({ size: 'A4', layout: 'landscape', margin: 36 });
      sy = 36;
      if (onNewPage) onNewPage(sy);
      sy = drawHead(sy);
      segTop = sy;
    }
    const fill = rowFill ? rowFill(idx, cells) : (idx % 2 === 0 ? PDF_STYLE.slate50 : '#FFFFFF');
    doc.rect(x, sy, tableW, rh).fill(fill);

    let cx = x;
    cells.forEach((val, i) => {
      const color = cellColor ? (cellColor(val, i, idx, cells) || PDF_STYLE.slate900) : PDF_STYLE.slate900;
      const raw = String(val ?? '');
      // Sel multi-baris (berisi \n) boleh wrap; sel biasa dipotong satu baris.
      const multiline = raw.includes('\n');
      doc.fillColor(color).fontSize(bodySize).font(boldCols.includes(i) ? 'Helvetica-Bold' : 'Helvetica')
        .text(raw, cx + 2, sy + PAD_Y, {
          width: cols[i] - 4,
          align: centerCols.includes(i) ? 'center' : 'left',
          ellipsis: !multiline,
          lineBreak: multiline,
          lineGap: LINE_GAP,
        });
      cx += cols[i];
    });

    // Garis pemisah antar baris (halus) + garis kolom vertikal tipis.
    doc.moveTo(x, sy + rh).lineTo(x + tableW, sy + rh)
      .lineWidth(0.4).stroke(PDF_STYLE.slate200);
    cx = x;
    for (let i = 0; i < cols.length - 1; i++) {
      cx += cols[i];
      doc.moveTo(cx, sy).lineTo(cx, sy + rh).lineWidth(0.3).stroke(PDF_STYLE.slate200);
    }
    sy += rh;
  });
  segments.push({ top: segTop, bottom: sy });

  // Border luar tabel, digambar per segmen halaman.
  segments.forEach((seg) => {
    doc.rect(x, seg.top, tableW, Math.max(0, seg.bottom - seg.top))
      .lineWidth(0.6).stroke(PDF_STYLE.slate200);
  });

  return { y: sy, tableW, shownCount: shown.length, totalRows: rows.length };
}

