// ─── Helper event: tanggal/hari/arah/ tipe user sesuai bahasa laporan ────────
// Event datang dari controller dengan `date` (fmtDateShort → bulan Indonesia),
// `dayOfWeek` (bahasa Indonesia) dan `direction` ('Masuk'/'Keluar'). Semua itu
// hardcoded Indonesia, sehingga laporan berbahasa English masih menampilkan
// "Nov"/"Senin"/"Masuk". Di sini kita normalkan ulang dari `dateKey` yang
// netral (YYYY-MM-DD) sehingga bisa diformat sesuai `lang`.
function evDateKey(ev) {
  if (!ev) return '';
  if (ev.dateKey) return ev.dateKey;
  if (ev.time) return dateKey(ev.time);
  return '';
}

/** Tanggal pendek event sesuai bahasa: "06 Nov 2026" (id) / "06 Nov 2026" (en) */
function evDateShort(ev, lang) {
  const dk = evDateKey(ev);
  if (dk) return fmtDateShortLang(dk, lang);
  return ev?.date || '-';
}

/** Nama hari event sesuai bahasa: "Rabu" (id) / "Wednesday" (en) */
function evDayName(ev, lang) {
  const dk = evDateKey(ev);
  if (dk) return dayName(dk, lang);
  return ev?.dayOfWeek || '-';
}

/** Arah absensi sesuai bahasa: "Masuk"/"Keluar" (id) / "In"/"Out" (en) */
function evDirection(ev, lang) {
  return ev?.deviceKey === 'masuk' ? txt(lang, 'directionIn') : txt(lang, 'directionOut');
}

/**
 * Label device sesuai bahasa.
 *
 * MASALAH: `deviceLabel` berasal dari server dan bernilai "Fingerprint Masuk" /
 * "Fingerprint Keluar" (hardcoded Indonesia). Dicetak apa adanya, laporan
 * berbahasa English tetap menampilkan teks Indonesia di kolom Device.
 *
 * SOLUSI: label device diturunkan ulang dari `deviceKey` (netral) memakai
 * kunci `dev.masuk` / `dev.keluar`. Bila deviceKey tidak dikenal, label asli
 * dibiarkan — lebih baik daripada menampilkan "-".
 */
function evDeviceLabel(ev, lang) {
  const key = ev?.deviceKey;
  if (key === 'masuk') return txt(lang, 'deviceIn');
  if (key === 'keluar') return txt(lang, 'deviceOut');
  return ev?.deviceLabel || ev?.deviceIP || '-';
}

/** Tipe user sesuai bahasa: "Normal"/"Administrator"/"Tamu" (id) */
function evUserType(userType, lang) {
  const raw = String(userType || 'Normal').toLowerCase();
  if (raw === 'administrator' || raw === 'admin') return txt(lang, 'administrator');
  if (raw === 'visitor' || raw === 'tamu') return txt(lang, 'visitor');
  return txt(lang, 'normal');
}

/** Waktu HH:MM event dalam WIB. Catatan: `timeFormatted` adalah ISO UTC,
 *  jadi slicing langsung menghasilkan jam UTC (7 jam mundur dari WIB).
 *  Sumber yang benar adalah `timeOnly` (sudah WIB dari controller), dan
 *  fallback harus lewat `fmtTime()` yang memang sudah mengonversi ke WIB. */
function evTimeOnly(ev) {
  if (!ev) return '-';
  if (ev.timeOnly) return String(ev.timeOnly).slice(0, 5);
  if (ev.time) {
    const t = fmtTime(ev.time);
    if (t && t !== '-') return t.slice(0, 5);
  }
  return '-';
}

/** Waktu HH:MM:SS event dalam WIB (dipakai agregasi & deteksi keterlambatan) */
function evTimeFull(ev) {
  if (!ev) return '';
  if (ev.timeOnly) return String(ev.timeOnly);
  if (ev.time) {
    const t = fmtTime(ev.time);
    if (t && t !== '-') return t;
  }
  return '';
}

function txt(lang, key) {
  return T[lang]?.[key] ?? T.en[key] ?? key;
}

// ─── Escape HTML untuk teks dari Pengaturan ────────────────────────────────────
//
// Judul/subjudul/footer laporan berasal dari input user (Pengaturan → Umum).
// Tanpa escape, teks seperti "<script>alert(1)</script>" akan dieksekusi saat
// laporan HTML dibuka di browser (pratinjau + email).
//
// Yang perlu di-escape HANYA teks yang masuk ke markup HTML. PDFKit dan
// ExcelJS aman secara bawaan — keduanya meloloskan karakter sebagai data,
// bukan sebagai markup.
//
// @param {unknown} s nilai apa pun
// @returns {string} teks yang aman disisipkan ke HTML
function escHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
  ));
}

// ─── Branding laporan (sumber tunggal untuk semua format) ──────────────────────
//
// Judul, subjudul, dan footer berasal dari Pengaturan → Umum. Semua format
// (PDF, HTML, Excel, Teks) WAJIB memakai objek yang sama supaya judulnya
// dijamin identik — kalau tiap format punya salinan logikanya sendiri, satu
// format bisa diam-diam menyimpang (bug class "format berbeda menampilkan
// judul berbeda").
//
// Urutan sumber judul (yang pertama terisi menang):
//   1. `report_title`    → "Judul Laporan"
//   2. judul bawaan      → "Laporan Absensi" / "Attendance Report"
// lalu nama perusahaan ditambahkan: "Laporan Absensi — PT Guard Test"
//
// Subjudul & footer bersifat opsional. Kalau kosong, teks bawaan (periode /
// "Dibuat oleh Sistem Absensi Fingerprint") tetap dipakai.
//
// @param {string} companyName nama perusahaan dari Pengaturan
// @param {{title?:string, subtitle?:string, footer?:string}} [branding]
// @returns {{companyName:string,title:string,subtitle:string,footer:string}}
export function buildBranding(companyName = '', branding = {}) {
  return {
    companyName: String(companyName || '').trim(),
    title:       String(branding?.title || '').trim(),
    subtitle:    String(branding?.subtitle || '').trim(),
    footer:      String(branding?.footer || '').trim(),
  };
}

function getDays(lang) {
  return lang === 'id' ? DAYS_ID : DAYS_EN;
}

function dayName(dateStr, lang) {
  // dateStr may be YYYY-MM-DD (dateKey) or Date object or already formatted string.
  // Handle Date objects first, then strings.
  if (!dateStr) return '-';
  let d;
  if (dateStr instanceof Date) {
    d = dateStr;
  } else {
    d = new Date(dateStr);
  }
  if (isNaN(d)) return '-';
  return getDays(lang)[d.getUTCDay()];
}

// ─── Per-employee aggregation ──────────────────────────────────────────────────
function aggregateByEmployee(events, lang, workStart = '09:00', detectLate = true, toleranceMinutes = 0) {
  // Use normName(name) as key — same as getRekap. This handles cases where
  // one person has multiple employeeNo across different devices (e.g. Juanto with
  // ID 5 on "masuk" device and ID 7 on "keluar" device). normName is defined
  // as: String(s||'').trim().replace(/\s+/g,' ').toLowerCase()
  const map = new Map();
  events.forEach(ev => {
    const evDisplayName = evName(ev);
    const nameKey = normName(evDisplayName || '');
    if (!map.has(nameKey)) {
      // Nomor awal juga harus CANONICAL. Kalau diisi dengan nomor lokal,
      // laporan menampilkan dua nomor untuk orang yang sama ("5, 6").
      const initialNo = ev.canonicalNo || ev.employeeNo;
      map.set(nameKey, {
        name:       evDisplayName,
        employeeNo: initialNo,
        userType:   evUserType(ev.userType, lang),
        allEmployeeNos: new Set([initialNo].filter(Boolean)),
        allEmployeeNo:  initialNo,
        masukList:  [],
        keluarList: [],
        masukWithDate: [],   // { time, dateKey } — dipakai untuk rincian keterlambatan
        daysSet:    new Set(),
        lateArrivals: [],
      });
    }
    const g = map.get(nameKey);
    // Merge all employeeNo into display.
    // Yang ditampilkan adalah nomor CANONICAL (nomor di perangkat referensi)
    // supaya satu orang tidak muncul dengan dua nomor berbeda.
    if (ev.employeeNo) {
      const canonicalNo = ev.canonicalNo || ev.employeeNo;
      g.allEmployeeNos.add(canonicalNo);
      g.allEmployeeNo = [...g.allEmployeeNos].join(', ');
    }
    const timeOnly = evTimeFull(ev);
    if (ev.deviceKey === 'masuk') {
      g.masukList.push(timeOnly);
      // Simpan tanggal WIB agar tabel "Rincian Keterlambatan" bisa
      // menampilkan tanggal spesifik, bukan hanya jam.
      g.masukWithDate.push({ time: timeOnly, dateKey: ev.dateKey || '' });
    }
    if (ev.deviceKey === 'keluar') g.keluarList.push(timeOnly);
    if (ev.dateKey) g.daysSet.add(ev.dateKey);
  });

  return [...map.values()].map(g => {
    const masukSorted   = [...g.masukList].filter(Boolean).sort();
    const keluarSorted  = [...g.keluarList].filter(Boolean).sort();
    const avgMasuk      = masukSorted.length ? avgTime(masukSorted) : txt(lang, 'notAvailable');
    // Tampilkan HH:MM (bukan HH:MM:SS) — kolom tabel dibuat setipis 6 karakter.
    const firstIn       = masukSorted[0]  ? String(masukSorted[0]).slice(0, 5)  : '-';
    const lastOut       = keluarSorted[keluarSorted.length - 1] ? String(keluarSorted[keluarSorted.length - 1]).slice(0, 5) : '-';

    // Build lateArrivals array: setiap hari karyawan masuk terlambat.
    // Hanya satu entri per hari (paling awal) — bila karyawan absen masuk
    // beberapa kali sehari, hanya yang pertama yang dihitung terlambat.
    // Tepat waktu dihitung dengan basis yang SAMA (pertama masuk per hari)
    // supaya lateCount + ontimeCount selalu sama dengan jumlah hari kerja.
    const firstInByDate = new Map();
    for (const m of g.masukWithDate) {
      if (!m.time) continue;
      const key = m.dateKey || m.time;
      const prev = firstInByDate.get(key);
      if (!prev || m.time < prev.time) firstInByDate.set(key, m);
    }
    const firstInPerDay = [...firstInByDate.values()].sort((a, b) =>
      (a.dateKey || a.time).localeCompare(b.dateKey || b.time),
    );

    const lateDays = [];
    if (detectLate) {
      for (const m of firstInPerDay) {
        const lm = calculateLateMinutes(m.time, workStart, toleranceMinutes);
        if (lm > 0) {
          lateDays.push({ time: m.time, lateMinutes: lm, dateKey: m.dateKey || '' });
        }
      }
    }

    const lateCount   = detectLate ? lateDays.length : 0;
    const ontimeCount = detectLate
      ? firstInPerDay.filter(m => m.time && calculateLateMinutes(m.time, workStart, toleranceMinutes) === 0).length
      : 0;

    return {
      name:        g.name,
      // Show all employeeNo IDs if multiple (handles same person on multiple devices)
      employeeNo:  g.allEmployeeNo,
      userType:    g.userType,
      totalAkses:  g.masukList.length + g.keluarList.length,
      masukCount:  g.masukList.length,
      keluarCount: g.keluarList.length,
      avgTime:     avgMasuk,
      firstIn,
      lastOut,
      hariHadir:   g.daysSet.size,
      daysList:    [...g.daysSet].sort().map(dk => fmtDateShortLang(dk, lang)).join(', '),
      lateArrivals: lateDays,
      lateCount,
      ontimeCount,
      lateMinutesTotal: detectLate ? lateDays.reduce((s, l) => s + l.lateMinutes, 0) : 0,
    };
  }).sort((a, b) => a.name.localeCompare(b.name));
}

// avgTime now exported for use in buildExportReport
function avgTime(times) {
  if (!times.length) return '-';
  const mins = times.map(t => {
    const [h, m] = t.split(':').map(Number);
    return h * 60 + m;
  });
  const avg = Math.round(mins.reduce((a, b) => a + b, 0) / mins.length);
  return `${String(Math.floor(avg / 60)).padStart(2, '0')}:${String(avg % 60).padStart(2, '0')}`;
}

// ─── Per-day aggregation ──────────────────────────────────────────────────────
function aggregateByDay(events, lang, workStart = '09:00', detectLate = true, toleranceMinutes = 0) {
  const map = new Map();
  events.forEach(ev => {
    // Use dateKey (YYYY-MM-DD) for reliable Date parsing — never ev.date (already formatted)
    const dk = ev.dateKey || dateKey(ev.time || ev.date);
    if (!map.has(dk)) {
      map.set(dk, {
        dateKey: dk,
        date: fmtDateShortLang(dk, lang),
        day: dayName(dk, lang),
        masukList: [],
        keluarList: [],
        lateEmployees: [],
      });
    }
    const g = map.get(dk);
    const timeOnly = evTimeFull(ev);
    if (ev.deviceKey === 'masuk') {
      g.masukList.push({ employeeNo: ev.employeeNo, name: evName(ev), time: timeOnly });
    }
    // Keluar disimpan sebagai objek (bukan string) supaya jumlah "org" di
    // kolom Keluar menghitung ORANG UNIK, bukan jam yang berbeda.
    // Sebelumnya `new Set(g.keluarList).size` menghitung jam unik sehingga
    // kolom Keluar selalu sama dengan jumlah event.
    if (ev.deviceKey === 'keluar') {
      g.keluarList.push({ employeeNo: ev.employeeNo, name: evName(ev), time: timeOnly });
    }
  });

  return [...map.values()]
    .sort((a, b) => a.dateKey.localeCompare(b.dateKey))
    .map(g => {
      // Sort masuk entries by time to find earliest per employee
      const sortedMasuk = [...g.masukList].sort((a, b) => a.time.localeCompare(b.time));
      // Unique employees who checked in (for masuk count) — use normKey to handle
      // same person with different employeeNo across devices (e.g. Juanto ID5/ID7)
      const uniqueMasukEmps = new Set(sortedMasuk.map(m => normKey(m)).filter(Boolean));
      // Unique employees who checked out — counted by person, not by timestamp.
      const uniqueKeluarEmps = new Set(
        g.keluarList.map(k => normKey(k)).filter(Boolean),
      );
      const keluarTimes = g.keluarList.map(k => k.time).filter(Boolean).sort();
      // Track late employees (first check-in per employee per day, by normName)
      const seenEmps = new Set();
      const lateEmployees = [];
      if (detectLate) {
        sortedMasuk.forEach(m => {
          if (!m.time) return;
          const empKey = normKey(m);
          if (!empKey) return;
          if (!seenEmps.has(empKey)) {
            seenEmps.add(empKey);
            const lm = calculateLateMinutes(m.time, workStart, toleranceMinutes);
            lateEmployees.push({ employeeNo: m.employeeNo, name: m.name, firstIn: m.time, lateMinutes: lm });
          }
        });
      }
      return {
        date:    g.date,
        day:     g.day,
        total:   g.masukList.length + g.keluarList.length,
        // Actual counts of unique employees who checked in/out that day
        masukCount:   uniqueMasukEmps.size,
        keluarCount:  uniqueKeluarEmps.size,
        firstIn:    sortedMasuk[0]?.time ? String(sortedMasuk[0].time).slice(0, 5) : '-',
        lastOut:    (() => {
          const lo = keluarTimes[keluarTimes.length - 1];
          return lo ? String(lo).slice(0, 5) : '-';
        })(),
        lateEmployees,
        lateCount: detectLate ? lateEmployees.filter(e => e.lateMinutes > 0).length : 0,
        ontimeCount: detectLate ? lateEmployees.filter(e => e.lateMinutes === 0).length : 0,
      };
    });
}

// ─── Verification mode breakdown ─────────────────────────────────────────────
function aggregateVerifyMode(events) {
  const counts = {};
  events.forEach(ev => {
    const vm = ev.verifyMode || 'Unknown';
    counts[vm] = (counts[vm] || 0) + 1;
  });
  return Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([mode, count]) => ({ mode, count }));
}

