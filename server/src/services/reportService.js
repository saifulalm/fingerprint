function evName(ev) {
  if (!ev) return '';
  return preferRealName(ev.name, ev.employeeName) || ev.name || '';
}

// ─── Late arrival config ───────────────────────────────────────────────────────
// Default threshold: 09:00 WIB (09:00 in 24h format)
const LATE_THRESHOLD_HOURS = process.env.LATE_THRESHOLD_HOURS || '09:00';

/**
 * Calculate late minutes given a first check-in time vs a threshold.
 * Returns 0 if not late, otherwise positive minutes late.
 *
 * @param {string} firstInTime  HH:MM
 * @param {string} threshold    HH:MM (default LATE_THRESHOLD_HOURS)
 * @param {number} toleranceMinutes  Menit toleransi keterlambatan. Karyawan
 *   yang terlambat <= toleransi dianggap TEPAT WAKTU (0 menit terlambat).
 *   Ini bersumber dari setting `late_threshold_minutes` di UI Pengaturan.
 * @returns {number} minutes late (0 if on time)
 */
export function calculateLateMinutes(firstInTime, threshold = LATE_THRESHOLD_HOURS, toleranceMinutes = 0) {
  if (!firstInTime || firstInTime === '-') return 0;
  const [fh, fm] = firstInTime.split(':').map(Number);
  const [th, tm] = threshold.split(':').map(Number);
  if (!Number.isFinite(fh) || !Number.isFinite(fm)) return 0;
  if (!Number.isFinite(th) || !Number.isFinite(tm)) return 0;
  const firstMins = fh * 60 + fm;
  const threshMins = th * 60 + tm;
  const rawLate = firstMins - threshMins;
  if (rawLate <= 0) return 0;
  // Kurangi toleransi. Bila terlambat tidak lebih dari toleransi, dianggap tepat.
  const tol = Number.isFinite(toleranceMinutes) && toleranceMinutes > 0 ? toleranceMinutes : 0;
  return Math.max(0, rawLate - tol);
}

